// Builds a self-contained SQL file that syncs scraped shops into `places`.
//
// Each mall row is found by a regex on its name, so it does not matter what
// the row was first called. If no row matches, one is inserted. If more than
// one matches, the whole script stops and nothing changes.

const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;

/**
 * @param {{ source: { name: string, match: RegExp, url: string }, shops: string[] }[]} results
 * @param {string} date
 */
export function buildSql(results, date) {
  const calls = results
    .map(({ source, shops }) => {
      return [
        `-- ${source.name}: ${shops.length} shops from ${source.url}`,
        `select pg_temp.apa_sync_place(`,
        `  ${lit(source.match.source)},`,
        `  ${lit(source.name)},`,
        `  ${lit(JSON.stringify(shops))}::jsonb`,
        `);`,
      ].join("\n");
    })
    .join("\n\n");

  return `-- Apa Makan: food directory sync, scraped ${date}.
-- Generated by scripts/scrape-places. Run it in the Supabase SQL editor.
-- Each call returns what it did ("updated <name>" or "inserted <name>").

begin;

create or replace function pg_temp.apa_sync_place(
  pattern text,
  canonical text,
  new_shops jsonb
) returns text
language plpgsql
as $fn$
declare
  matches int;
  target text;
  col_type text;
  shops_expr text;
begin
  select count(*), min(name) into matches, target
  from public.places
  where name ~* pattern;

  if matches > 1 then
    raise exception 'More than one row in places matches "%". Nothing was changed.', pattern;
  end if;

  select data_type into col_type
  from information_schema.columns
  where table_schema = 'public' and table_name = 'places' and column_name = 'shops';

  shops_expr := case col_type
    when 'ARRAY' then 'array(select jsonb_array_elements_text($1))'
    when 'json' then '$1::json'
    else '$1'
  end;

  if matches = 1 then
    execute format('update public.places set shops = %s where name = $2', shops_expr)
      using new_shops, target;
    return 'updated ' || target;
  end if;

  execute format('insert into public.places (name, shops) values ($2, %s)', shops_expr)
    using new_shops, canonical;
  return 'inserted ' || canonical;
end;
$fn$;

${calls}

commit;
`;
}
